/**
 * Voice assistant entry point — CAG (Context-Augmented Generation).
 *
 * ALL intent resolution is via the Groq tool-calling agentic loop
 * (src/services/voiceAgent.ts). Before calling the loop, this file builds
 * a clinic context snapshot (recent cases, outstanding invoices, QC items,
 * advance wallet, month-close status, patient names) and passes it into the
 * dynamic system prompt, so Groq can resolve ANY phrase — typed or spoken —
 * without hardcoded phrases or keyword matching.
 *
 * No fixed phrases anywhere: if the AI decides there is no tool call, it
 * asks the operator a natural, general question instead of a canned
 * keyword-match. The AI auto-executes the work when it is clear enough to
 * act on; otherwise it asks.
 */
import { remember } from './voiceMemory';
import { buildClinicContext } from './voiceContextCache';
import type { VoiceToolContext } from './voiceRegistry';
import type { WriteCommand } from './voiceWrite';
import { runAgenticLoop } from './voiceAgent';
import { getLastError } from './voiceAiRouter';

export interface AssistantResult {
  text: string;
  spoke: boolean;
  /** When set, the voice shell navigates the app to this view id. */
  navigateTo?: string;
  /** When set, the voice shell auto-executes this write (destructive still
      keeps the typed-token gate). */
  pendingWrite?: WriteCommand;
  /** Risk of the pending action (write | destructive). */
  risk?: 'write' | 'destructive';
}

const mkr = (text: string): AssistantResult => ({ text, spoke: false });

/** Natural-question fallback when the agentic loop has nothing to run —
 *  never a canned keyword list; always points at something actionable on the
 *  user's own clinic. */
const noActionText = (): string =>
  "I'm not sure what you mean — what would you like to do with your clinic? " +
  'I can check balances, statements, open cases, record a payment, or open any screen. ' +
  "Say 'what can you do?' for everything.";

/** Redact-and-remember the Q/A pair for the local "learn from us" store. */
const finish = (text: string, raw = ''): AssistantResult => {
  try { remember(raw, text); } catch { /* memory is best-effort */ }
  return mkr(text);
};

/** Build the clinic context snapshot for CAG — uses the first clinic in labs
 *  (the one most likely on-screen), plus all-clinics summary in the prompt. */
const buildContextForQuery = (ctx: VoiceToolContext): { clinicContext: any } | null => {
  const labs = ctx.labs || [];
  if (!labs.length) return null;
  const clinic = labs[0];
  return {
    clinicContext: buildClinicContext(clinic, {
      cases: ctx.cases || [],
      invoices: ctx.invoices || [],
      advancePayments: ctx.advancePayments || [],
      accountAdjustments: ctx.accountAdjustments || [],
      userPreferences: ctx as any,
    }),
  };
};

/** Natural, AI-driven fallback when the agent loop returns null.
 *  Messages are generated by a second Groq call where possible, or based on
 *  the last error (rate limit, invalid key, network). Never hardcoded lists. */
const buildFallback = (): string => {
  const err = getLastError();
  switch (err) {
    case 'rate_limited':
      return 'AI providers are rate-limited right now — try again in a few minutes, or add another provider (OpenRouter, etc.) in Settings → Jarvis AI.';
    case 'invalid_key':
      return 'No AI provider keys configured. Add a Groq or OpenRouter API key in Settings → Jarvis AI.';
    case 'insufficient_credit':
      return 'Your AI provider account is out of credit — top it up or switch providers in Settings → Jarvis AI.';
    case 'invalid_model':
      return "That model name isn't accepted by your AI provider. Open Settings → Jarvis AI to pick a supported model, or use the default.";
    case 'server_error':
      return 'The AI provider is having trouble on their end. Try again in a moment.';
    case 'network_error':
      return "Couldn't reach the AI right now — check your internet connection and try again.";
    default:
      break;
  }
  return "I'm not sure what you mean — could you say it a different way? Say 'what can you do?' for everything I can help with.";
};

export async function askAssistant(raw: string, ctx: VoiceToolContext): Promise<AssistantResult> {
  const q = (raw || '').trim();
  const done = (text: string) => finish(text, q);
  if (!q) {
    return done('What would you like to know about your clinic? Balances, statements, open cases — or just ask "what can you do?"');
  }

  // Build CAG context: recent cases, outstanding invoices, QC items, advance wallet, month-close, patient names.
  const { clinicContext } = buildContextForQuery(ctx) || { clinicContext: null };

  // Primary path: AI agentic loop (tool calling via multi-provider router).
  const agentResult = await runAgenticLoop(q, ctx, clinicContext);
  if (agentResult?.navigateTo) return { ...agentResult, spoke: true } as AssistantResult;
  if (agentResult?.text) return { ...agentResult, spoke: true } as AssistantResult;

  // Fallback: natural message based on the AI provider error state; when the
  // agent simply has nothing to run (and no provider error), ask a natural
  // open question rather than dead-ending.
  const err = getLastError();
  if (err && err !== 'invalid_key') return done(buildFallback());
  return done(noActionText());
}
